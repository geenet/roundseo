/**
 * robots.txt Generator
 * Builds a valid robots.txt from the page inventory.
 * Rules: TECH-005 (permit crawling), TECH-008 (valid robots.txt)
 *
 * Limits: 500 KiB interpreted size (Google stops reading after that).
 * Google follows the last matching rule, so more-specific Allow rules
 * override broad Disallow rules when placed before them.
 */

import { pageInventory } from './inventory';

const ROBOTS_MAX_BYTES = 500 * 1024; // 500 KiB

export interface RobotsConfig {
  sitemapUrl?: string;
  /** Explicit additional Disallow paths beyond what the inventory provides */
  extraDisallow?: string[];
  /** Explicit Allow overrides (e.g. allow /api/health for monitoring) */
  extraAllow?: string[];
  /** Crawl-delay for non-Googlebot crawlers (seconds). Googlebot ignores this. */
  crawlDelay?: number;
}

/**
 * Derive Disallow paths from the page inventory.
 * private and noindex pages must NOT be disallowed (Google needs to read
 * the noindex directive, TECH-007), but auth/admin routes that have no
 * public value should be disallowed for all bots.
 *
 * We only disallow `private` routes (auth walls, admin panels).
 * `noindex` routes are intentionally left crawlable so Google can read
 * the directive and honour the exclusion – blocking them in robots.txt
 * would violate TECH-007.
 */
function deriveDisallowPaths(): string[] {
  const paths = new Set<string>();

  for (const page of pageInventory) {
    if (page.indexing_intent === 'private') {
      // Normalise wildcard patterns: /admin/* → /admin/
      const path = page.url.endsWith('/*')
        ? page.url.slice(0, -1) // keep trailing slash
        : page.url.endsWith('*')
          ? page.url.slice(0, -1)
          : page.url;
      paths.add(path);
    }
  }

  return Array.from(paths).sort();
}

/**
 * Build the robots.txt text content.
 */
export function generateRobotsTxt(config: RobotsConfig = {}): string {
  const disallow = [
    ...deriveDisallowPaths(),
    ...(config.extraDisallow ?? []),
  ];

  const allow = config.extraAllow ?? [];

  const lines: string[] = [
    '# robots.txt generated by roundseo SEO framework',
    `# Generated: ${new Date().toISOString()}`,
    '',
    'User-agent: *',
  ];

  for (const path of allow) {
    lines.push(`Allow: ${path}`);
  }

  for (const path of disallow) {
    lines.push(`Disallow: ${path}`);
  }

  if (config.crawlDelay !== undefined && config.crawlDelay > 0) {
    lines.push(`Crawl-delay: ${config.crawlDelay}`);
  }

  if (config.sitemapUrl) {
    lines.push('');
    lines.push(`Sitemap: ${config.sitemapUrl}`);
  }

  lines.push('');

  return lines.join('\n');
}

/**
 * Validate robots.txt content.
 * Returns a list of issues, empty when valid.
 */
export function validateRobotsTxt(content: string): string[] {
  const issues: string[] = [];
  const bytes = new TextEncoder().encode(content).length;

  if (bytes > ROBOTS_MAX_BYTES) {
    issues.push(
      `robots.txt is ${bytes} bytes, exceeding the 500 KiB limit (${ROBOTS_MAX_BYTES} bytes). Google stops reading at the limit.`
    );
  }

  // Detect patterns that block all crawling
  const lines = content.split('\n').map((l) => l.trim());
  let currentAgents: string[] = [];

  for (const line of lines) {
    if (line.startsWith('#') || line === '') {
      if (line === '') currentAgents = [];
      continue;
    }

    const [field, ...rest] = line.split(':');
    const value = rest.join(':').trim();

    if (field.toLowerCase() === 'user-agent') {
      currentAgents.push(value);
    }

    if (field.toLowerCase() === 'disallow') {
      const blocksAll = value === '/' || value === '/*';
      if (blocksAll && (currentAgents.includes('*') || currentAgents.includes('Googlebot'))) {
        issues.push(
          `Disallow: ${value} under User-agent: ${currentAgents.join(', ')} blocks all crawling. This prevents Google from indexing any page.`
        );
      }
    }
  }

  if (!content.includes('User-agent:')) {
    issues.push('robots.txt has no User-agent directive. At minimum include "User-agent: *".');
  }

  return issues;
}

/**
 * Build the HTTP Response for GET /robots.txt
 */
export function buildRobotsTxtResponse(config: RobotsConfig = {}): Response {
  const content = generateRobotsTxt(config);
  const issues = validateRobotsTxt(content);

  if (issues.length > 0) {
    console.error('[SEO] robots.txt validation issues:', issues);
  }

  return new Response(content, {
    status: 200,
    headers: {
      'Content-Type': 'text/plain; charset=utf-8',
      'Cache-Control': 'public, max-age=3600',
    },
  });
}
